"""Raw-source status audit. Never recover a withheld component."""
import json
from pathlib import Path

LABELS={'reported':'Reported','withheld':'Withheld by DESE','not_applicable':'Not applicable','not_supplied':'Not in supplied source','pending':'Awaiting confirmation'}
FIELDS={'FRL %':'LUNCH_COUNT_FREE_REDUCED_PCT','EL %':'ELL_LEP_STUDENTS_ENROLLED_K_12_PCT','IEP incidence %':'IEP_INCIDENCE_RATE','Black %':'ENROLLMENT_BLACK_PCT','Hispanic %':'ENROLLMENT_HISPANIC_PCT','Multiracial %':'ENROLLMENT_MULTIRACIAL_PCT','White %':'ENROLLMENT_WHITE_PCT'}

def raw_status(row,field):
    return 'reported' if row.get(field) is not None else 'withheld' if row.get('_missingness',{}).get(field,{}).get('reason')=='suppressed_in_source' else 'not_supplied'

def audit(payload,tables,root):
    codes={s['DESE LEA'] for s in payload['schools']};keys={(b['lea'],b['building']) for b in payload['directory']};cells=[]
    for level,file in [('School','dese_district_demographics_1991_2025.xlsx'),('Building','dese_building_demographics_2006_2025.xlsx')]:
        for row in tables[file]['Sheet1']:
            lea=str(row['COUNTY_DISTRICT_CODE']).zfill(6);b=str(row['SCHOOL_CODE']).zfill(4) if level=='Building' else None
            if row['YEAR']!=2025 or lea not in codes or b and (lea,b) not in keys:continue
            for metric,field in FIELDS.items():cells.append(dict(level=level,year=2025,lea=lea,building=b,metric=metric,status=raw_status(row,field),source=file,row=row['_row']))
    for level,expected,n in [('School',5,42),('Building',10,98)]:
        rows=[c for c in cells if c['level']==level];assert len(rows)==n
        assert sum(c['status']=='withheld' for c in rows)==expected
        assert all(c['status'] in ('reported','withheld') for c in rows),'Unexpected truly blank demographic source cell'
    school_fixture={('048925',m) for m in ('EL %','Multiracial %','White %')}|{('115926',m) for m in ('EL %','Hispanic %')}
    assert {(c['lea'],c['metric']) for c in cells if c['level']=='School' and c['status']=='withheld'}==school_fixture
    building_fixture={('048914','1910','EL %'),('115926','6905','EL %'),('115926','6905','Hispanic %'),('115911','6955','EL %'),('048922','1920','Multiracial %'),('048922','3940','Multiracial %'),('048922','3940','White %'),('048925','6985','EL %'),('048925','6985','Multiracial %'),('048925','6985','White %')}
    assert {(c['lea'],c['building'],c['metric']) for c in cells if c['level']=='Building' and c['status']=='withheld'}==building_fixture
    for r in payload['assessments']:
        if r['category']!='MSIP Total' or r['group']!='Total':continue
        st='reported' if r['PA_PCT'] is not None else 'withheld' if any(r['missingness'].get(k,{}).get('reason')=='suppressed_in_source' for k in ['PROFICIENT','ADVANCED']) else 'not_supplied'
        r['status']=st
        cells.append(dict(level='School' if r['level']=='Charter' else 'Building',year=2025,lea=r['lea'],building=r['building'],metric='MAP '+r['subject'],status=st,source=r['source_file'],row=r['source_row']))
    for r in payload['growth']:
        r['status']='reported' if r['eligible'] else 'not_applicable' if (r['lea'],r['building'])==('115911','6955') else 'not_supplied'
        cells.append(dict(level='Building',year=2025,lea=r['lea'],building=r['building'],metric='Growth '+r['subject'],status=r['status'],source=r['source_file'],row=r['source_row']))
    for subject in ['Eng. Language Arts','Mathematics']:
        cells.append(dict(level='Building',year=2025,lea='115911',building='6955',metric='MAP '+subject,status='not_applicable',source='dese_map_2025_school_content_area.xlsx',row=None))
    for output,level,key in [(payload['schools'],'School','School'),(payload['buildings'],'Building','Building name')]:
        for row in output:
            matched=[c for c in cells if c['level']==level and c['lea']==row['DESE LEA'] and (level=='School' or c['building']==str(row['Building code']).zfill(4))]
            row['statuses']={c['metric']:c['status'] for c in matched}
            for metric,subject in [('MAP ELA P+A %','Eng. Language Arts'),('MAP Math P+A %','Mathematics')]:row['statuses'][metric]=next((c['status'] for c in matched if c['metric']=='MAP '+subject),'not_supplied')
    payload['status_vocabulary']=LABELS
    (root/'qa/missing-data-audit.json').write_text(json.dumps({'vocabulary':LABELS,'cells':cells},indent=2),encoding='utf-8')
    text=['# Missing-data audit','','Generated by rereading the raw DESE workbook rows during the build. No suppression cause is inferred.','','| Level | Metric | Identifier | Year | Status | Source / row |','| --- | --- | --- | --- | --- | --- |']
    text += [f"| {c['level']} | {c['metric']} | {c['lea']}/{c['building'] or '-'} | {c['year']} | {LABELS[c['status']]} | {c['source']} / {c['row'] or 'no applicable row'} |" for c in cells if c['status']!='reported']
    text+=['','School demographics: 5 withheld of 42; Building demographics: 10 withheld of 98. All other checked demographic cells reported.','City Garden ECEC MAP and growth: Not applicable; no tested-grade MAP row and blank growth fields.','The Biome PK: Not in supplied source. All master PK–12 totals blank. Raw preliminary files missing; owner Harshil.','Physical campus count and internal OSCP program/operations figures: Awaiting confirmation; see validated CSV inputs.']
    (root/'docs/internal/missing-data-audit.md').write_text('\n'.join(text)+'\n',encoding='utf-8')
    return cells

def annotate(value):
    """Every nullable field carries a companion status; numeric zero stays reported."""
    if isinstance(value,list):
        for v in value:annotate(v)
    elif isinstance(value,dict):
        nulls=[k for k,v in value.items() if v is None]
        if nulls:
            statuses=value.setdefault('statuses',{})
            for k in nulls:
                reason=value.get('missingness',{}).get(k,{})
                columns=value.get('source_columns',[])
                if columns:
                    source_field=columns[0] if k=='numerator' else columns[-1] if k=='published_pct' else columns[1] if k=='denominator' and len(columns)==3 else None
                    if source_field:reason=value.get('missingness',{}).get(source_field,reason)
                    if k=='value' and any(v.get('reason')=='suppressed_in_source' for v in value.get('missingness',{}).values()):reason={'reason':'suppressed_in_source'}
                statuses.setdefault(k,'not_applicable' if k=='building' else value.get('status') if value.get('status') in ('not_applicable','pending') else 'pending' if value.get('display_status')=='pending' else 'withheld' if reason.get('reason')=='suppressed_in_source' or k=='PA_PCT' and value.get('status')=='withheld' else 'not_supplied')
                assert statuses[k] in LABELS
        for k,v in list(value.items()):
            if k!='statuses':annotate(v)

def validate_nulls(value,path=''):
    if isinstance(value,list):
        for i,v in enumerate(value):validate_nulls(v,f'{path}/{i}')
    elif isinstance(value,dict):
        for k,v in value.items():
            if v is None:assert value.get('statuses',{}).get(k) in LABELS, f'Null without status: {path}/{k}'
            elif k!='statuses':validate_nulls(v,f'{path}/{k}')
